/**
 * 变异跑到一半被打断时,把动过的源文件还回去。
 *
 * `mutate.ts` 每应用一个变异就**改写一份真实源文件**,跑完测试再由 `finally` 改回来。
 * **信号杀进来时 `finally` 不跑** —— Ctrl-C、被杀掉、CI 超时、终端关掉,没人接管这几个
 * 信号时 Node 当场结束进程,`finally` 和挂在退出上的清理一个都不执行。那一刻留在
 * 工作区里的,是一处**故意违反某条需求的改动**,而没有任何东西说过它在那儿。
 *
 * 它有多难被发现:下一次 `npm run check` 报的是「锚点失效,未能应用」——
 * 一句指着变异集的话,而错的是上一次没跑完。中间要是把工作区整个提交上去,
 * 进去的就是那处改动。
 *
 * **挡不住硬杀和断电** —— 那时没有任何代码跑得起来。和落盘那边「先写临时文件
 * 再改名」同一个形状:能挡的是「被打断」,不是「被硬杀」,差额明写在这里,不假装。
 *
 * 抽成模块而不是写在入口里:什么时候该写回、什么时候不该,是判定,
 * 而判定写在入口脚本里就永远测不到(`docs/CONVENTIONS.md` 第 10 条)。
 */
import { writeFileSync } from 'node:fs'
import type { ChildProcess } from 'node:child_process'

/** 正被改写的那个源文件和它的原文。没有变异在跑的时候是 undefined */
let inFlight: { file: string; orig: string } | undefined

/** 信号接管过了没有 */
let armed = false

/**
 * 要开始改这个文件了 —— 记下现场,好让被打断的时候有东西可还。
 *
 * **接管信号也在这一步。** 「记下现场」和「从这一刻起被打断要还回去」是同一件事,
 * 拆成两次调用,入口少写一行就是一整轮变异没人接管信号地跑完,而模块这边每条断言
 * 照样全绿 —— 评审指出的正是这个缺口。合成一次之后,那一行不存在了,也就忘不掉。
 */
export function beginMutation(file: string, orig: string): void {
  restoreOnInterrupt()
  inFlight = { file, orig }
}

/**
 * 把现场还回去。跑完一个变异走这里,被信号打断也走这里 —— **只此一条还原路径**;
 * 两边各写一份的话,总有一边会在下一次改动之后被忘掉。
 *
 * 没有现场就什么都不写。**打断的时机完全可能落在还没开始应用变异的那一段**
 * (读登记表、查变异集记在谁名下),那时盘上本来就是干净的;而照着一个不存在的
 * 现场去写,只会在信号处理里当场抛 —— 还原没做成,退出也没走成,覆盖记录跟着
 * 一起留在盘上,而人看到的是一堆栈,像是变异集自己坏了。
 *
 * 写之前先把现场清掉:还原过的就没有什么可还的了,再调一次不该再写一遍。
 */
export function restoreMutation(): void {
  const cur = inFlight
  if (cur === undefined) return
  inFlight = undefined
  writeFileSync(cur.file, cur.orig, 'utf8')
}

/**
 * 正在跑的那一轮测试子进程。**没有测试在跑的时候必须是 undefined。**
 *
 * 这不是一句描述,是那一刀的前提:组号只在那个组还在的时候才指得着它。
 * 一轮跑完之后不抹掉的话,从这一轮结束到下一轮记上之间那段空档里,它拿着的是一个
 * 已经散了的组号 —— 而组号是系统会重新发给别人的。这时候被打断,那一刀就落到
 * 一个不相干的进程身上,而落到谁身上是不响的(评审指出)。信号处理是整轮都装着的,
 * 所以这段空档整轮都在。
 */
let running: ChildProcess | undefined

/**
 * 这一轮的测试子进程交给这里看着 —— 被打断时要连它一起结束。
 *
 * **父进程退掉不会把它带走。** 它会被过继出去接着跑:实测父进程退出之后八百毫秒,
 * 它照样往盘上写了一次。而变异跑的正是被改过的源码,它那一次写下的东西谁也没审过 ——
 * 覆盖记录尤其如此:入口把那一份的还原挂在退出上,还原跑完之后它再写一遍,
 * 盘上留下的就是一份由被改过的源码产生的记录,而后面的审计会拿它当真的用(评审指出)。
 *
 * 上一版同步等子进程的时候没有这个窗口 —— 那时子进程跑完了才轮到父进程往下走。
 * **是换成异步等之后才有的**,所以补在这里。
 *
 * **结束了要抹掉,而且抹的时候要认人。** 不抹,空档里留下的是一个散了的组号;
 * 不认人,上一轮迟到的那次结束会把下一轮刚记上的抹没,那一刀又落空 —— 两头都是
 * 不响的(评审指出)。
 */
export function trackTest(kid: ChildProcess): void {
  running = kid
  kid.on('close', () => { if (running === kid) running = undefined })
}

/**
 * 现在还有没有一轮测试被看着。
 *
 * **只为了「结束了要抹掉」这件事能被看见才导出的**,别处不用它。不导出的话,
 * 上面那句「没有测试在跑的时候必须是 undefined」就只是一句注释:抹掉那一行删了,
 * 没有任何一条断言会红。
 */
export function testRunning(): boolean {
  return running !== undefined
}

/**
 * 结束正在跑的那一轮测试。**杀的是整个进程组,不是手上那一个。**
 *
 * 只杀手上那一个不够:拿到的往往只是层壳,真正跑脚本的是壳再分出去的那个进程。
 * 实测过 —— 杀掉壳,里面那个照样把三秒之后那一次写盘做完,而「杀掉了吗」这个
 * 返回值还是真。所以入口那边让它自成一组,这里连组一起杀。
 *
 * **这两半必须一起在。** 入口那边少了「自成一组」,这个组号就没有对应的组,
 * 那一刀落空 —— 而落空是不响的。如实说明:没有任何东西会提醒。
 *
 * 组早就散了会报「查无此组」,那正是想要的状态,所以吞掉。
 *
 * **这一刀发出去就走,不等那一组真停下。** 硬杀拦不住,但从发出去到真停下还有一小段,
 * 那一刻已经交给内核的那一次写盘照样会落在盘上。**等不到**:孙子那一层不是这个进程
 * 生的,它咽气的消息送不到这里;而拿号码轮询「还在不在」在这个环境里不作数 ——
 * 被杀掉的进程会一直挂在表里(实测)。何况真去等,「挨刀的那一刻当场就停」那条判据
 * 就不成立了,而硬杀升上来的时候工作区里留着的正是被改过的源码。
 * 所以如实记下这一条:**留在盘上的至多是一次已经在路上的写,不是八百毫秒的自由活动**
 * (评审指出,已答复)。
 */
function killTest(): void {
  const pid = running?.pid
  if (pid === undefined) return
  try { process.kill(-pid, 'SIGKILL') } catch { /* 组已经散了 */ }
}

/**
 * 被打断时该做的:先停掉那一轮测试,再还原,最后退出。
 *
 * **顺序是定死的。** 反过来先还原的话,从还原完到进程真退掉之间那一小段里,
 * 它还醒着、还在跑被改过的源码,还能再往盘上写一遍 —— 还原就白做了。
 *
 * 退出码非零 —— 这一次检查没跑完,不能算过。
 * 走 `process.exit` 而不是就地结束,是因为入口还把覆盖记录的还原挂在退出上:
 * 那一份原先也只在正常跑完时才还得回去,这一步顺带把它接上。
 */
export function onInterrupt(): never {
  killTest()
  restoreMutation()
  process.exit(1)
}

/**
 * 装上信号处理。**三种都要装**:Ctrl-C 是一种,被杀掉和 CI 超时是另一种,
 * 终端关掉是第三种 —— 只接管其中一种,另外两条路照样把改动留在工作区里。
 *
 * **装过就不再装。** 每个变异都要记一次现场,两百个变异装两百遍的话,同一个信号上
 * 挂满处理函数,Node 开始刷告警 —— 而那时被盖住的,正是人来看的那份变异结果。
 */
export function restoreOnInterrupt(): void {
  if (armed) return
  armed = true
  for (const sig of ['SIGINT', 'SIGTERM', 'SIGHUP'] as const) process.on(sig, onInterrupt)
}

/**
 * 同步等子进程的那几个写法。**名字后面要跟着左括号** —— 文字里提到它们不算,
 * 只有真的调用才算,否则连解释这条规矩的那段注释都会把自己判红。
 */
const BLOCKING_WAIT = /\b(execSync|execFileSync|spawnSync)\s*\(/

/**
 * 接管了信号的那个入口,有没有同步等子进程。撞上了返回那个名字,没撞上返回 undefined。
 *
 * **接管信号和同步等子进程不能同时存在。** 信号处理是排在事件循环上的,同步等会把
 * 循环整个挡住;挡住的那段时间里,接管过的信号一次也派发不出去。而变异跑起来之后
 * 几乎所有时间都在等子进程 —— 挡住的正是要接管的那一段。
 *
 * 更糟的是接管本身把默认动作压住了:没接管时 Ctrl-C 当场就结束进程;接管之后默认动作
 * 不作数,而处理函数又轮不上,那一刀于是被整个吞掉,循环把剩下两百个变异跑完,还以零
 * 退出 —— 一次没跑完的检查报成过了。**所以这是接管顺手带来的回归,不是它没管到的
 * 地方**,判据也就跟着接管一起放在这里(评审指出)。
 *
 * 判的是源文件的字面形状,和 `lint-rule.ts` 同一路数:不剥注释、不解析,逐行逐字地找。
 * 会不会误伤一段正好这么写的注释?会 —— 那时改注释,不改判据。
 */
export function blockingWait(src: string): string | undefined {
  const hit = BLOCKING_WAIT.exec(src)
  return hit === null ? undefined : hit[1]
}
