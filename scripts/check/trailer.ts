/**
 * 提交信息的 **trailer 块** —— 末尾那一段 `Key: value`。
 *
 * 闸门要在提交信息里读指令(体量豁免、分支寿命豁免),而提交信息里也会**举例**
 * 说明这些指令怎么写。分不开的话,后果是双向的:
 *
 * - 写对的示例 → 白送一条豁免,超线的改动靠「文档里举了个例子」混过闸门
 * - 故意写歪的示例 → 让闸门报红。这一种真发生过:一次提交信息里用缩进举了
 *   两个反例,CI 当场红
 *
 * 判据借的是 **git 自己的 trailer 定义**,不是自攒的:最后一段、整段每一行都是
 * `Key: value`。这个模块是那条判据的唯一实现 —— 第二个闸门要用同一条判据时,
 * 抄一份是让它们迟早分家,所以抽在这里。
 *
 * 走到这一步之前试过五种更窄的补法(要求顶格 → 排除引文 → 认围栏 → 认围栏的
 * 种类与闭合 → 认 HTML 注释),每一版都被下一种写法打回。**换判据比补判据管用:
 * 规范自带边界,自攒的判据没有。**
 */

/** 一行 trailer 的形状。`size-ok`、`Co-Authored-By` 都是这个形状。 */
const TRAILER = /^[\w.-]+:\s/

/**
 * 取出指令区的各行。不是 trailer 块就返回空 —— **宁可少认,不可错认**:
 * 少认一条豁免的代价是闸门报红、人补一条;错认一条的代价是超线的改动溜过去。
 */
export function trailerLines(message: string): string[] {
  const blocks = message.replace(/\s+$/, '').split(/\n[ \t]*\n/)
  const last = (blocks[blocks.length - 1] ?? '').split('\n').filter(l => l.trim())
  /**
   * 最后一段必须**整段都是 trailer**,才算指令区。
   *
   * 只取「最后一段」还不够:一条以示例结尾、后面没有 trailer 的提交信息,
   * 那个示例就成了最后一段。而围栏行、`<!--`、散文都不是 `Key: value` 的形状 ——
   * 用形状把整段挡掉,比再去遮罩段内的引文简单,也不必再枚举引文的写法。
   */
  if (!last.length || !last.every(l => TRAILER.test(l))) return []
  return last
}
